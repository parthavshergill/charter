"""Write attention_layout.h from rl/layout.json, so the CUDA encoder knows where each table is.

Usage: python gen_layout.py LAYOUT_JSON OUT_HEADER [--moves]

One-row tables are the context; the others are tokens. `--moves` keeps the optional `moves` table (only when
the environment runs with per-move rows on, which round 1 does not).
"""
import json
import sys


def main(argv):
    layout = json.load(open(argv[0]))
    moves = "--moves" in argv
    obs_size = layout["full_size"] if moves else layout["base_size"]
    ctx, tok = [], []
    for t in layout["tables"]:
        if t["offset"] + t["rows"] * t["width"] > obs_size:
            continue
        (ctx if t["rows"] == 1 else tok).append(t)
    lst = lambda xs: ", ".join(str(x) for x in xs)
    out = [
        "// Generated by gen_layout.py from rl/layout.json. Do not edit.",
        f"// layout version {layout['version']}, obs_size {obs_size}",
        "#pragma once",
        f"#define CA_LAYOUT_VERSION {layout['version']}",
        f"#define CA_OBS_SIZE {obs_size}",
        f"#define CA_N_CTX {len(ctx)}",
        f"#define CA_CTX_OFF_LIST {lst(t['offset'] for t in ctx)}",
        f"#define CA_CTX_W_LIST {lst(t['width'] for t in ctx)}",
        f"#define CA_CTX_W {sum(t['width'] for t in ctx)}",
        f"#define CA_N_TAB {len(tok)}",
        f"#define CA_TAB_OFF_LIST {lst(t['offset'] for t in tok)}",
        f"#define CA_TAB_ROWS_LIST {lst(t['rows'] for t in tok)}",
        f"#define CA_TAB_W_LIST {lst(t['width'] for t in tok)}",
        f"#define CA_N_TOK {sum(t['rows'] for t in tok)}",
        f"// token tables: {lst(t['name'] for t in tok)}; context: {lst(t['name'] for t in ctx)}",
        "",
    ]
    open(argv[1], "w").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:])
