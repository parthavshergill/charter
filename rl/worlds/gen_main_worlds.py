"""Write rl/lean/CharterRL/MainWorlds.lean from rl/worlds/main/, the nine shipped worlds as `main` has them.

    python3 rl/worlds/gen_main_worlds.py          # write it
    python3 rl/worlds/gen_main_worlds.py --check  # fail if the file differs from what this would write

`rl/worlds/main/<World>.lean`, `Spec.lean` and `PreviewCheck.lean` are `main`'s `Charter/Games/<World>.lean`,
`Server/Spec.lean` and `Server/PreviewCheck.lean` at the commit in `MAIN_COMMIT`. Each world's file is copied up to
and including its `G.Valid` theorem (`by decide +kernel`, checked again when this library builds), in the namespace
`CharterRL.MainWorlds.<World>`. What comes after it (the look, the meshes) is not needed and not copied. The seat
range comes from `Spec.lean` and the laws a table can be asked to vote on from `PreviewCheck.lean`'s `lawsFor`, as
`main` has them. The worlds get ids `main-<id>`, so they never mix with this branch's own copies.

To update: copy the files from `main` again (see the README) and run this.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "main")
OUT = os.path.join(HERE, "..", "lean", "CharterRL", "MainWorlds.lean")

# world file, its game, its theorem, its spec name in Spec.lean, its id
WORLDS = [
    ("Island", "island", "island_valid", "islandSpec", "island"),
    ("NotCatan", "game", "game_valid", "notCatanSpec", "not-catan"),
    ("SlimeParliament", "game", "game_valid", "slimeSpec", "slime-parliament"),
    ("AIBubble", "game", "game_valid", "bubbleSpec", "ai-bubble"),
    ("StrikeTheEarth", "game", "game_valid", "strikeSpec", "strike-the-earth"),
    ("PirateRepublic", "game", "game_valid", "pirateSpec", "pirate-republic"),
    ("ThePit", "game", "game_valid", "pitSpec", "the-pit"),
    ("Omerta", "game", "game_valid", "omertaSpec", "omerta"),
    ("HillAndChill", "game", "game_valid", "hillSpec", "hill-and-chill"),
]


def world_body(name, theorem):
    text = open(os.path.join(SRC, f"{name}.lean")).read()
    m = re.search(rf"^theorem {theorem} :[^\n]*\n", text, re.M)
    assert m, f"{name}: no theorem {theorem}"
    head = text[:m.end()]
    lines = [l for l in head.splitlines() if not l.startswith("import ")]
    head = "\n".join(lines).strip() + "\n"
    old = f"namespace Charter.Games.{name}\n"
    assert head.count(old) == 1, name
    return head.replace(old, f"namespace CharterRL.MainWorlds.{name}\nopen Charter Charter.Games\n") + \
        f"\nend CharterRL.MainWorlds.{name}\n"


def seats(spec_text, spec):
    m = re.search(rf"^def {spec} : GameSpec :=\n(.*?)(?=^def |\Z)", spec_text, re.M | re.S)
    assert m, spec
    body = m.group(1)
    lo = re.search(r"minSeats := (\d+)", body)
    hi = re.search(r"maxSeats := (\d+)", body)
    return int(lo.group(1)) if lo else 2, int(hi.group(1)) if hi else 6


def laws(preview_text):
    """The law texts of `lawsFor`, by spec name; `else` is the list for every other spec."""
    m = re.search(r"^def lawsFor \(spec : GameSpec\) : List String :=\n(.*?)\n\n", preview_text, re.M | re.S)
    assert m, "lawsFor"
    body = m.group(1)
    heads = list(re.finditer(r"^\s*(?:(?:if|else if) spec\.id == (\w+)\.id then|(else))\n", body, re.M))
    out = {}
    for i, h in enumerate(heads):
        key = h.group(1) or "else"
        end = heads[i + 1].start() if i + 1 < len(heads) else len(body)
        out[key] = re.findall(r'^\s*[\[,] "((?:[^"\\]|\\.)*)"', body[h.end():end], re.M)
    return out


def lean_str(s):
    return '"' + s + '"'


def render():
    commit = open(os.path.join(SRC, "MAIN_COMMIT")).read().strip()
    spec_text = open(os.path.join(SRC, "Spec.lean")).read()
    by_spec = laws(open(os.path.join(SRC, "PreviewCheck.lean")).read())
    out = [f"/- Generated by rl/worlds/gen_main_worlds.py from rl/worlds/main/ (`main` at {commit[:12]}).",
           "   Do not edit: copy the files from `main` again and run the script. -/",
           "import Charter.Words", "import Charter.Games.HexMap", ""]
    for name, game, theorem, spec, wid in WORLDS:
        out.append(world_body(name, theorem))
    out += ["namespace CharterRL.MainWorlds", "open Charter", "",
            "/-- A shipped world as `main` has it: its id, the game, its seat range, the laws a table can vote on, "
            "and its spots on the hex grid. -/",
            "structure World where", "  id : String", "  G : GameDef", "  minSeats : Nat", "  maxSeats : Nat",
            "  laws : List String", "  spots : List HexGrid.Vertex", "", "/-- The nine. -/",
            "def worlds : List World :=", "  ["]
    rows = []
    for name, game, theorem, spec, wid in WORLDS:
        lo, hi = seats(spec_text, spec)
        texts = by_spec.get(spec, by_spec["else"])
        lawlist = ", ".join(lean_str(t) for t in texts)
        rows.append(f"    {{ id := \"main-{wid}\", G := {name}.{game}, minSeats := {lo}, maxSeats := {hi}\n"
                    f"      laws := [{lawlist}]\n      spots := {name}.spots }}")
    out.append("\n  , ".join(rows).replace("    {", "{", 1).join(["    ", ""]) if False else "    " + "\n  , ".join(r.strip() for r in rows))
    out += ["  ]", "", "end CharterRL.MainWorlds", ""]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("MainWorlds.lean is up to date" if same else "MainWorlds.lean differs: run rl/worlds/gen_main_worlds.py")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
