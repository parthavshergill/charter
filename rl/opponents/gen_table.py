"""Write rl/lean/CharterRL/TableBot.lean from rl/opponents/table/, the table bot as `main` has it.

    python3 rl/opponents/gen_table.py          # write it
    python3 rl/opponents/gen_table.py --check  # fail if the file differs from what this would write

`rl/opponents/table/BotCore.lean` and `GameFacts.lean` are `main`'s `Server/BotCore.lean` and
`Server/GameFacts.lean` at the commit in `MAIN_COMMIT`: the bot the server seats today (`Bots.candidatesFor` calls
its `handEvents`). They are copied as they are, in the namespace `CharterRL.Table`, so that they live only in the
training library, beside `rl-harness`'s own older copy of the bot (`hand`). To update, copy the two files again from
`main` and run this.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "table")
OUT = os.path.join(HERE, "..", "lean", "CharterRL", "TableBot.lean")


def body(path, old_ns, new_ns):
    text = open(os.path.join(SRC, path)).read()
    lines = [l for l in text.splitlines() if not l.startswith("import ")]
    text = "\n".join(lines).strip() + "\n"
    assert text.count(f"namespace {old_ns}\n") == 1 and text.count(f"end {old_ns}\n") == 1, path
    return text.replace(f"namespace {old_ns}\n", f"namespace {new_ns}\n").replace(f"end {old_ns}\n", f"end {new_ns}\n")


def render():
    commit = open(os.path.join(SRC, "MAIN_COMMIT")).read().strip()
    head = (f"/- Generated by rl/opponents/gen_table.py from rl/opponents/table/ (`main` at {commit[:12]}).\n"
            "   Do not edit: copy the files from `main` again and run the script. -/\n"
            "import Charter.Scene.OfState\nimport Server.MoveJson\n\n")
    facts = body("GameFacts.lean", "CharterServer", "CharterRL.Table")
    core = body("BotCore.lean", "CharterServer.Bots", "CharterRL.Table.Bots")
    return head + facts + "\n" + core


def main():
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("TableBot.lean is up to date" if same else "TableBot.lean differs: run rl/opponents/gen_table.py")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
