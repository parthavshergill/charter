#!/usr/bin/env python3
"""Generate what Lean's Comparator reads: Comparator/Challenge.lean and comparator.json.

The challenge holds the same theorem statements as the source files, each with `sorry` as its proof.
It imports only the words, the engine and the named parts, so it never sees a proof.

    python3 scripts/comparator_challenge.py write    writes the two files from the source files.
    python3 scripts/comparator_challenge.py check    fails if the two files are out of date.

To add a theorem from a new file, add the file to SOURCES. A new theorem in a listed file comes in by
itself. Comparator then checks that each statement really means the same in both places.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHALLENGE = ROOT / "Comparator" / "Challenge.lean"
CONFIG = ROOT / "comparator.json"

SOURCES = [
    "Charter/Constitution.lean",
    "Charter/Constitution/Supporting.lean",
    "Charter/Proofs/Witness.lean",
    "Charter/Proofs/IslandWitness.lean",
    "Server/SecrecyPromise.lean",
]
# Helper lemmas that promise nothing by themselves.
SKIP = {"witness_of_check"}
IMPORTS = ["Charter.Constitution.Promises", "Charter.Games.Witnesses", "Charter.Games.Island", "Server.Secrecy"]
AXIOMS = ["propext", "Quot.sound", "Classical.choice"]

OPENERS = {"(": ")", "[": "]", "{": "}", "⟨": "⟩"}
CLOSERS = set(OPENERS.values())


def statement_end(text: str, start: int) -> int:
    """Return the place of the first `:=` outside all brackets. That is where the proof starts."""
    depth = 0
    for i in range(start, len(text)):
        c = text[i]
        if c in OPENERS:
            depth += 1
        elif c in CLOSERS:
            depth -= 1
        elif depth == 0 and text.startswith(":=", i):
            return i
    raise SystemExit(f"no `:=` after position {start}")


def read_source(rel: str):
    """Return the opening lines, the (name, statement) pairs and the closing lines of one file."""
    text = (ROOT / rel).read_text(encoding="utf-8")
    if re.search(r"^(variable|section|universe|local|attribute|notation|macro)\b", text, re.M):
        raise SystemExit(f"{rel}: has a command that can change a statement's meaning. Handle it here.")
    openers = re.findall(r"^(?:namespace|open) .*$", text, re.M)
    closers = re.findall(r"^end .*$", text, re.M)
    namespaces = re.findall(r"^namespace (\S+)$", text, re.M)
    if len(namespaces) != 1:
        raise SystemExit(f"{rel}: expected one namespace, found {namespaces}")
    # A theorem in any other form would drop out of the challenge with no error.
    other = re.search(r"^(?!theorem\s)[ \t]*(?:@\[[^\]\n]*\][ \t]*)*(?:(?:private|protected|public)[ \t]+)*(?:theorem|lemma)\s", text, re.M)
    if other:
        raise SystemExit(f"{rel}: this script reads only a plain `theorem` at the start of a line, not: {other.group(0).strip()}")
    theorems = []
    for m in re.finditer(r"^theorem\s+(\S+)", text, re.M):
        if m.group(1) in SKIP:
            continue
        statement = text[m.start() : statement_end(text, m.end())].rstrip()
        theorems.append((f"{namespaces[0]}.{m.group(1)}", statement))
    return openers, theorems, closers


def generate():
    out = [
        "-- Generated by scripts/comparator_challenge.py. Do not edit this file.",
        "-- The statements are copied from the source files. The proofs are left out on purpose.",
    ]
    out += [f"import {name}" for name in IMPORTS]
    names = []
    for rel in SOURCES:
        openers, theorems, closers = read_source(rel)
        out += ["", f"-- From {rel}", ""] + openers
        for name, statement in theorems:
            names.append(name)
            out += ["", f"{statement} :=", "  sorry"]
        out += [""] + closers
    if len(set(names)) != len(names):
        raise SystemExit("two theorems have the same name")
    config = {
        "challenge_module": "Comparator.Challenge",
        "solution_module": "Comparator.Solution",
        "theorem_names": names,
        "permitted_axioms": AXIOMS,
    }
    return "\n".join(out) + "\n", json.dumps(config, indent=2) + "\n"


def main():
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    challenge, config = generate()
    if mode == "write":
        CHALLENGE.parent.mkdir(exist_ok=True)
        CHALLENGE.write_text(challenge, encoding="utf-8")
        CONFIG.write_text(config, encoding="utf-8")
        print(f"Wrote {len(json.loads(config)['theorem_names'])} statements.")
    elif mode == "check":
        for path, want in ((CHALLENGE, challenge), (CONFIG, config)):
            if not path.exists() or path.read_text(encoding="utf-8") != want:
                raise SystemExit(f"{path.name} is out of date. Run: python3 scripts/comparator_challenge.py write")
        print(f"The challenge matches the source files: {len(json.loads(config)['theorem_names'])} statements.")
    else:
        raise SystemExit("usage: comparator_challenge.py write|check")


main()
